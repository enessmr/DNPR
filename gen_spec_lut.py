#!/usr/bin/env python3
"""Bake the kernel's exact 8-bit normal highlight into a boot-time blob."""

import math
import pathlib
import zlib

import numpy as np


ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "kernel/dnpr_spec_blob.h"


def main():
    axis = np.arange(-128, 128, dtype=np.int64)
    y = axis[:, None]
    z = axis[None, :]
    table = bytearray(256**3)
    for xi, x in enumerate(axis):
        length = np.sqrt(x * x + y * y + z * z).astype(np.int64)
        dot = -59 * x + 41 * y + 106 * z
        h = np.where((dot > 0) & (length > 0), dot // np.maximum(length, 1), 0)
        q = np.minimum(h, 127) * 65536 // 127
        for _ in range(7):
            q = q * q >> 16
        spec = (90 * q >> 16).astype(np.uint8)
        table[xi * 65536 : (xi + 1) * 65536] = spec.tobytes()

    # Check boundary and random entries against scalar integer arithmetic.
    import random
    rng = random.Random(0xD4A9)
    for _ in range(100_000):
        x, y, z = (rng.randrange(-128, 128) for _ in range(3))
        length = math.isqrt(x*x + y*y + z*z)
        h = (-59*x + 41*y + 106*z) // length if length else 0
        q = min(h, 127) * 65536 // 127 if h > 0 else 0
        for _ in range(7):
            q = q * q >> 16
        expected = 90 * q >> 16
        actual = table[((x+128) << 16) | ((y+128) << 8) | (z+128)]
        if actual != expected:
            raise RuntimeError(f"LUT mismatch at {(x,y,z)}: {actual} != {expected}")

    compressor = zlib.compressobj(level=9, wbits=-15)
    blob = compressor.compress(table) + compressor.flush()
    lines = ["/* Generated by gen_spec_lut.py; exact dnpr_specular output. */",
             "static const unsigned char dnpr_spec_deflate[] = {"]
    for i in range(0, len(blob), 24):
        lines.append("\t" + ", ".join(f"0x{v:02x}" for v in blob[i:i+24]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(table)} bytes of lookup data; {len(blob)} bytes compressed")


if __name__ == "__main__":
    main()
