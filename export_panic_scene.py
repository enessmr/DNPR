#!/usr/bin/env python3
"""Bake the preloaded kernel panic scene: base frame plus animated sprite layers.

The kernel inflates this blob during boot and composites the sprite layers live
during a panic. The base is the 1920x1080 preview pose without overlays
(background plus the head frozen on frame 130); the layers are the silver star,
the red star (pre-tinted the way dnpr-test tints it at draw time), both sparkle
sets, and the prompt glyphs, all 128x128 RGBA.
"""
import argparse
import struct
import zlib
from pathlib import Path

import numpy as np

parser = argparse.ArgumentParser()
parser.add_argument('scene', type=Path)
parser.add_argument('header', type=Path)
args = parser.parse_args()

STAR_FRAMES = 8
SPARKLE_FRAMES = 6
GLYPH_FRAMES = 11
SPRITE = 128
SPRITE_BYTES = SPRITE * SPRITE * 4
BG_BYTES = 4 * 1200 * 300 * 3

magic0 = struct.unpack('<I', b'DNPR')[0]
magic1 = struct.unpack('<I', b'K001')[0]

def tint_red(frame):
    out = bytearray(frame)
    for i in range(0, len(out), 4):
        out[i + 1] = out[i + 1] // 6
        out[i + 2] = out[i + 2] // 8
    return bytes(out)


# scene.bin: header, 4 background rows, 16 star frames (8 silver, 8 red — both
# stored untinted; dnpr-test only tints the red sparkles at draw time),
# 11 glyphs at 16x16, 11 glyphs at 128x128, 6 sparkles at 32x32,
# 6 sparkles at 128x128. The kernel layers use the 128x128 variants only.
with args.scene.open('rb') as f:
    if f.read(8) != b'DNPRS005' or struct.unpack('<IIII', f.read(16)) != (1200, 300, 128, 128):
        raise SystemExit(f'invalid scene asset {args.scene}')
    bg = np.frombuffer(f.read(BG_BYTES), dtype=np.uint8)
    if bg.size != BG_BYTES:
        raise SystemExit('truncated scene asset')
    bg = bg.reshape(4, 300, 1200, 3)

    # Build the panic base from the tiled background alone. A preview frame
    # contains the frozen final-pose head; embedding it here leaves a large
    # prerendered face behind while the live mesh starts small and animates.
    ys = np.arange(1080)
    xs = np.arange(1920)
    rows = (ys * 12 // 1080) % 4
    sy = (ys * 12 * 300 // 1080) % 300
    sx = (xs * 1200 // 480) % 1200
    rgb = bg[rows[:, None], sy[:, None], sx[None, :]]
    rgb565 = (((rgb[:, :, 0].astype(np.uint16) >> 3) << 11) |
              ((rgb[:, :, 1].astype(np.uint16) >> 2) << 5) |
              (rgb[:, :, 2].astype(np.uint16) >> 3)).astype('<u2')
    payload = bytearray(rgb565.tobytes())

    stars = f.read(16 * SPRITE_BYTES)
    if len(stars) != 16 * SPRITE_BYTES:
        raise SystemExit('truncated star frames')
    f.seek(GLYPH_FRAMES * 16 * 16 * 4, 1)
    glyphs = f.read(GLYPH_FRAMES * SPRITE_BYTES)
    if len(glyphs) != GLYPH_FRAMES * SPRITE_BYTES:
        raise SystemExit('truncated prompt glyphs')
    f.seek(SPARKLE_FRAMES * 32 * 32 * 4, 1)
    sparkles = f.read(SPARKLE_FRAMES * SPRITE_BYTES)
    if len(sparkles) != SPARKLE_FRAMES * SPRITE_BYTES:
        raise SystemExit('truncated sparkle frames')

payload += stars  # the red star PNGs are already red; dnpr-test draws stars untinted
payload += sparkles
payload += tint_red(sparkles)  # dnpr-test only tints the red branch's sparkles
payload += glyphs

compressor = zlib.compressobj(level=9, wbits=-15)
blob = compressor.compress(payload) + compressor.flush()
with args.header.open('w') as out:
    out.write('/* Generated by export_panic_scene.py; raw DEFLATE RGB565 base + RGBA layers. */\n')
    out.write('struct dnpr_blob_meta {\n'
              '\tunsigned int magic0, magic1;\n'
              '\tunsigned int base_w, base_h;\n'
              '\tunsigned int star_frames, star_size;\n'
              '\tunsigned int sparkle_frames, sparkle_size;\n'
              '\tunsigned int glyph_frames, glyph_size;\n'
              '};\n')
    out.write('static const struct dnpr_blob_meta dnpr_frame_meta = {\n'
              f'\t0x{magic0:x}u, 0x{magic1:x}u, 1920, 1080,\n'
              f'\t{STAR_FRAMES}, {SPRITE}, {SPARKLE_FRAMES}, {SPRITE}, {GLYPH_FRAMES}, {SPRITE},\n'
              '};\n')
    out.write('static const unsigned char dnpr_frame_deflate[] = {\n')
    for offset in range(0, len(blob), 16):
        out.write('    ' + ', '.join(f'0x{x:02x}' for x in blob[offset:offset + 16]) + ',\n')
    out.write('};\n')
print(f'{len(payload)} bytes RGB565 base + {STAR_FRAMES + SPARKLE_FRAMES * 2 + GLYPH_FRAMES} '
      f'sprite layers -> {len(blob)} bytes preloaded scene')
